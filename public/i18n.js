export function detectLocale(stored, browserLanguage = "") {
  if (stored === "zh" || stored === "en") return stored;
  return browserLanguage.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function createTranslator(locale) {
  return (key, variables = {}) => {
    const template = messages[locale]?.[key] ?? messages.zh[key] ?? key;
    return Object.entries(variables).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template,
    );
  };
}

export function translateServerError(message, locale) {
  if (locale === "zh" || typeof message !== "string") return message;
  return serverErrors[message] || message;
}

